import Foundation

/// Diagnostic playback processing. The original WAV is always preserved.
enum AudioSignal {
    enum Mode: String, Sendable {
        case original, corrected, enhanced, adaptive

        var title: String {
            switch self {
            case .original: "原音"
            case .corrected: "通常補正"
            case .enhanced: "比較用120Hz補正"
            case .adaptive: "標準補正"
            }
        }
        var details: String {
            switch self {
            case .original: "受信時の音声"
            case .corrected: "16bit DC補正・16kHz"
            case .enhanced: "16bit DC補正・16kHz・120Hzハイパス・約18dB増幅・ピーク抑制"
            case .adaptive: "16bit DC補正・16kHz・30Hzハイパス・自動音量（最大17倍）"
            }
        }
    }
    struct Analysis: Sendable {
        let frames: Int
        let sampleRate: Int
        let dc: Double
        let acRMS: Double
        let peak: Int
        let clippingFraction: Double
        let zeroFraction: Double
        let wrappedSamples: Int

        var summary: String {
            let level = acRMS > 0 ? String(format: "%.1f dBFS", 20 * log10(acRMS / 32768)) : "無音"
            return String(format: "音声診断: %dサンプル / %d Hz・DC %.0f・AC音量 %@・最大振幅 %d・飽和 %.1f%%・ゼロ %.1f%%・16bit補正 %dサンプル",
                          frames, sampleRate, dc, level, peak, clippingFraction * 100, zeroFraction * 100, wrappedSamples)
        }
    }
    struct Prepared: Sendable {
        let wav: Data
        let analysis: Analysis
        let appliedGain: Double?
        init(wav: Data, analysis: Analysis, appliedGain: Double? = nil) {
            self.wav = wav; self.analysis = analysis; self.appliedGain = appliedGain
        }
    }
    enum SignalError: Error { case invalidWAV, tooLarge }
    static let maximumBytes = 32 * 1024 * 1024

    /// Reads only the canonical mono PCM16 WAV format generated by this app.
    private static func decode(_ wav: Data) throws -> (pcm: Data, rate: Int) {
        guard wav.count >= 44, wav.count <= maximumBytes + 44 else { throw SignalError.invalidWAV }
        let bytes = [UInt8](wav.prefix(44))
        func uint(_ offset: Int, _ count: Int) -> Int {
            (0..<count).reduce(0) { $0 | Int(bytes[offset + $1]) << (8 * $1) }
        }
        guard Array(bytes[0..<4]) == Array("RIFF".utf8),
              Array(bytes[8..<16]) == Array("WAVEfmt ".utf8),
              Array(bytes[36..<40]) == Array("data".utf8),
              uint(4, 4) == wav.count - 8, uint(16, 4) == 16,
              uint(20, 2) == 1, uint(22, 2) == 1, uint(34, 2) == 16,
              uint(32, 2) == 2, uint(40, 4) == wav.count - 44,
              (1_000...192_000).contains(uint(24, 4)),
              uint(28, 4) == uint(24, 4) * 2,
              wav.count > 44, (wav.count - 44).isMultiple(of: 2)
        else { throw SignalError.invalidWAV }
        return (Data(wav.dropFirst(44)), uint(24, 4))
    }

    static func prepare(wav: Data, mode: Mode = .corrected) throws -> Prepared {
        let (pcm, rate) = try decode(wav)
        let bytes = [UInt8](pcm)
        let frames = bytes.count / 2
        func sample(_ i: Int) -> Int {
            Int(Int16(bitPattern: UInt16(bytes[2 * i]) | UInt16(bytes[2 * i + 1]) << 8))
        }
        var sum: Int64 = 0
        var squares = 0.0
        var peak = 0
        var clipped = 0
        var zeros = 0
        for i in 0..<frames {
            if i.isMultiple(of: 4096) { try Task.checkCancellation() }
            let value = sample(i)
            sum += Int64(value)
            squares += Double(value) * Double(value)
            peak = max(peak, abs(value))
            if value == Int(Int16.min) || value == Int(Int16.max) { clipped += 1 }
            if value == 0 { zeros += 1 }
        }
        let dc = Double(sum) / Double(frames)
        let bias = Int(dc.rounded())
        var wrappedSamples = 0
        for i in 0..<frames {
            if i.isMultiple(of: 4096) { try Task.checkCancellation() }
            let shifted = sample(i) - bias
            if shifted < -32768 || shifted > 32767 { wrappedSamples += 1 }
        }
        // The receiver library's bias subtraction preserves the 16-bit bit pattern.
        // Correct BEFORE interpolation; clamping here changes boundary crossings into clicks.
        func centeredSample(_ index: Int) -> Double {
            Double(Int16(truncatingIfNeeded: sample(index) - bias))
        }
        let analysis = Analysis(frames: frames, sampleRate: rate, dc: dc,
            acRMS: sqrt(max(0, squares / Double(frames) - dc * dc)), peak: peak,
            clippingFraction: Double(clipped) / Double(frames), zeroFraction: Double(zeros) / Double(frames), wrappedSamples: wrappedSamples)
        if mode == .original { return Prepared(wav: wav, analysis: analysis) }
        let outputRate = 16_000
        let count = max(1, Int((Double(frames) * Double(outputRate) / Double(rate)).rounded()))
        guard count <= maximumBytes / 2 else { throw SignalError.tooLarge }
        var corrected = Data()
        corrected.reserveCapacity(count * 2)
        // Linear interpolation for the diagnostic comparison, with no gain or silence removal.
        // Preserve real timing: do not merely replace the WAV sample-rate header.
        for i in 0..<count {
            if i.isMultiple(of: 4096) { try Task.checkCancellation() }
            let position = Double(i) * Double(rate) / Double(outputRate)
            let left = min(Int(position), frames - 1)
            let right = min(left + 1, frames - 1)
            let fraction = position - Double(left)
            let value = centeredSample(left) * (1 - fraction) + centeredSample(right) * fraction
            let clamped = Int16(max(-32768, min(32767, value.rounded())))
            let bits = UInt16(bitPattern: clamped)
            corrected.append(UInt8(truncatingIfNeeded: bits))
            corrected.append(UInt8(truncatingIfNeeded: bits >> 8))
        }
        if mode == .adaptive {
            let result = try adaptive(corrected, sampleRate: outputRate)
            return Prepared(wav: try PCM16WAV.encode(pcm: result.pcm, sampleRate: outputRate),
                            analysis: analysis, appliedGain: result.gain)
        }
        let outputPCM = mode == .enhanced ? try enhance(corrected, sampleRate: outputRate) : corrected
        return Prepared(wav: try PCM16WAV.encode(pcm: outputPCM, sampleRate: outputRate), analysis: analysis)
    }
    /// Fourth-order 120 Hz Butterworth high-pass, +18.06 dB, smooth 90%-FS limiter.
    /// Matches the comparison file the user found more intelligible; no speech synthesis.
    private static func enhance(_ pcm: Data, sampleRate: Int) throws -> Data {
        let bytes = [UInt8](pcm)
        let frames = bytes.count / 2
        func sample(_ i: Int) -> Double {
            Double(Int16(bitPattern: UInt16(bytes[2 * i]) | UInt16(bytes[2 * i + 1]) << 8))
        }
        var first = HighPass(sampleRate: Double(sampleRate), q: 0.541196100146197,
                             initialInput: sample(0))
        var second = HighPass(sampleRate: Double(sampleRate), q: 1.306562964876377,
                              initialInput: 0)
        let limit = 0.9 * 32767.0
        var output = Data()
        output.reserveCapacity(pcm.count)
        for i in 0..<frames {
            if i.isMultiple(of: 4096) { try Task.checkCancellation() }
            let filtered = second.process(first.process(sample(i)))
            let limited = limit * tanh(8 * filtered / limit)
            let value = Int16(max(-32768, min(32767, limited.rounded())))
            let bits = UInt16(bitPattern: value)
            output.append(UInt8(truncatingIfNeeded: bits))
            output.append(UInt8(truncatingIfNeeded: bits >> 8))
        }
        return output
    }

    /// Matches the locally generated 30 Hz comparison that the user could understand.
    /// Quantize between the two sections, then choose one gain for the whole recording.
    /// Do not normalize quiet frames separately or synthesize sound from silence.
    private static func adaptive(_ pcm: Data, sampleRate: Int) throws -> (pcm: Data, gain: Double) {
        let bytes = [UInt8](pcm)
        var first = HighPass(sampleRate: Double(sampleRate), q: 0.541196100146197,
                             initialInput: 0, cutoff: 30)
        var second = HighPass(sampleRate: Double(sampleRate), q: 1.306562964876377,
                              initialInput: 0, cutoff: 30)
        func quantize(_ value: Double) -> Int16 {
            Int16(max(-32768, min(32767, value.rounded(.towardZero))))
        }
        var filtered: [Int16] = []
        filtered.reserveCapacity(bytes.count / 2)
        for i in stride(from: 0, to: bytes.count, by: 2) {
            if i.isMultiple(of: 8192) { try Task.checkCancellation() }
            let sample = Int16(bitPattern: UInt16(bytes[i]) | UInt16(bytes[i + 1]) << 8)
            let intermediate = quantize(first.process(Double(sample)))
            filtered.append(quantize(second.process(Double(intermediate))))
        }
        let frameSize = max(1, sampleRate / 50) // 20 ms, including any final partial frame.
        var voicedSquares = 0.0
        var voicedCount = 0
        for offset in stride(from: 0, to: filtered.count, by: frameSize) {
            try Task.checkCancellation()
            let end = min(offset + frameSize, filtered.count)
            var squares = 0.0
            for i in offset..<end { squares += Double(filtered[i]) * Double(filtered[i]) }
            if sqrt(squares / Double(end - offset)) > 100 {
                voicedSquares += squares; voicedCount += end - offset
            }
        }
        let rms = voicedCount > 0 ? sqrt(voicedSquares / Double(voicedCount)) : 0
        let gain = rms > 0 ? max(1, min(17, 7000 / rms)) : 1
        var output = Data(); output.reserveCapacity(pcm.count)
        for (i, sample) in filtered.enumerated() {
            if i.isMultiple(of: 4096) { try Task.checkCancellation() }
            let value = quantize(Double(sample) * gain)
            let bits = UInt16(bitPattern: value)
            output.append(UInt8(truncatingIfNeeded: bits))
            output.append(UInt8(truncatingIfNeeded: bits >> 8))
        }
        return (output, gain)
    }

    private struct HighPass {
        private let b0: Double
        private let b1: Double
        private let b2: Double
        private let a1: Double
        private let a2: Double
        private var z1: Double
        private var z2: Double

        init(sampleRate: Double, q: Double, initialInput: Double, cutoff: Double = 120) {
            let omega = 2 * Double.pi * cutoff / sampleRate
            let cosine = cos(omega)
            let alpha = sin(omega) / (2 * q)
            b0 = (1 + cosine) / (2 * (1 + alpha))
            b1 = -(1 + cosine) / (1 + alpha)
            b2 = b0
            a1 = -2 * cosine / (1 + alpha)
            a2 = (1 - alpha) / (1 + alpha)
            // Start at the first sample's DC steady state, avoiding an added leading click.
            z1 = -b0 * initialInput
            z2 = b2 * initialInput
        }

        mutating func process(_ input: Double) -> Double {
            let value = b0 * input + z1
            z1 = b1 * input - a1 * value + z2
            z2 = b2 * input - a2 * value
            return value
        }
    }

}
